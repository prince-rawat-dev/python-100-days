n1 = int(input("Enter a 1st no. : "))
n2 = int(input("Enter a 2nd no. : "))

def add():
    return n1+n2
def subtract():
    return n1-n2
def multiply():
    return n1*n2
def divide():
    return n1/n2

print("Addtion is", add())
print("Subtraction is", subtract())
print("Multiplication is", multiply())
print("Division is", divide())